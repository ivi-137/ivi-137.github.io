const GLOBAL_ORDER = ['clockRate', 'clockSync', 'clockDiv', 'swing', 'scale', 'root', 'drift', 'cutoff', 'reso', 'revMix', 'revSize', 'revDamp', 'master'];

/** A preset exactly as written, which may ask for a little more than a knob can give. */
export function presetRaw(i: number): Float64Array {
  const p = PRESETS[Math.min(PRESETS.length - 1, Math.max(0, i))];
  const v = defaults();
  p.agents.forEach((a, n) => a.forEach((x, k) => (v[AGENT0 + n * AGENT_STRIDE + k] = x)));
  p.gens.forEach(([mult, prob], g) => {
    v[GEN0 + g * 2] = mult;
    v[GEN0 + g * 2 + 1] = prob;
  });
  GLOBAL_ORDER.forEach((id, k) => (v[PIDX[id]] = p.g[k]));
  return v;
}

/**
 * A preset as a full parameter array, held to each parameter's range. A few presets ask for a rise time
 * past the knob's two seconds; the plugin clamps those the same way. Anything a preset does not name keeps
 * its default (the tempo, for one).
 */
export function presetValues(i: number): Float64Array {
  return presetRaw(i).map((x, k) => snap(PARAMS[k], x));
}

